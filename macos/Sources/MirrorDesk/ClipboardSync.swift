import Foundation
import AppKit

/// Decides what crosses between the Mac and phone clipboards. Pure logic, so tests drive it
/// without a pasteboard or a phone.
public struct ClipboardSyncState: Sendable {
    /// Text both sides already hold. Never sent again in either direction, which stops echo loops
    /// (Mac sets phone, phone poll reports it back, Mac sets phone, ...).
    public private(set) var lastSynced: String?

    public init() {}

    /// The Mac clipboard changed. Returns the text to send to the phone, or nil.
    public mutating func macChanged(to text: String?) -> String? {
        guard let text, !text.isEmpty, text != lastSynced else { return nil }
        lastSynced = text
        return text
    }

    /// The phone reported its clipboard. Returns true when the Mac pasteboard should take it.
    public mutating func phoneChanged(to text: String) -> Bool {
        guard !text.isEmpty, text != lastSynced else { return false }
        lastSynced = text
        return true
    }
}

/// Pasteboard types that password managers set to ask other apps not to copy the item.
/// See nspasteboard.org.
public enum PasteboardMarkers {
    public static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public static func shouldSkip(types: [String]) -> Bool {
        types.contains { skipped.contains($0) }
    }
}

/// Keeps the Mac and phone clipboards in step over a `ScrcpyControlSession`.
///
/// macOS has no pasteboard change notification, so this polls `changeCount` every 0.5 s,
/// which costs one integer read per tick.
@MainActor
public final class ClipboardBridge {
    private let session: ScrcpyControlSession
    private let pasteboard: NSPasteboard
    private var state = ClipboardSyncState()
    private var lastChangeCount: Int
    private var timer: Timer?

    public var onStatus: ((String) -> Void)?

    public init(session: ScrcpyControlSession, pasteboard: NSPasteboard = .general) {
        self.session = session
        self.pasteboard = pasteboard
        self.lastChangeCount = pasteboard.changeCount
    }

    public func start() async throws {
        session.onMessage = { [weak self] message in
            guard case .clipboard(let text) = message else { return }
            Task { @MainActor in self?.receivedFromPhone(text) }
        }
        session.onClose = { [weak self] reason in
            Task { @MainActor in
                self?.timer?.invalidate()
                self?.onStatus?("Clipboard sync stopped: \(reason)")
            }
        }
        try await session.start()
        // Whatever the Mac holds now is the starting point; do not push it to the phone.
        _ = state.macChanged(to: pasteboard.string(forType: .string))
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.pollPasteboard() }
        }
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
        session.stop()
    }

    private func pollPasteboard() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let types = pasteboard.types?.map(\.rawValue) ?? []
        guard !PasteboardMarkers.shouldSkip(types: types) else { return }
        if let text = state.macChanged(to: pasteboard.string(forType: .string)) {
            session.send(ScrcpyControlWire.setClipboard(text, paste: false))
        }
    }

    private func receivedFromPhone(_ text: String) {
        guard state.phoneChanged(to: text) else { return }
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        // Our own write bumps changeCount; record it so the poll does not treat it as a Mac copy.
        lastChangeCount = pasteboard.changeCount
    }
}
