import Testing
import Foundation
@testable import MirrorFSExtension

@Suite("Pasteboard Privacy Filter Tests")
struct PasteboardPrivacyTests {
    let filter = PasteboardPrivacyFilter()

    @Test("Filters out ConcealedType and 1Password types")
    func testConcealedAndSensitiveTypesFiltered() {
        let sensitiveCases: [[String]] = [
            ["org.nspasteboard.ConcealedType", "public.utf8-plain-text"],
            ["com.agilebits.onepassword", "public.utf8-plain-text"],
            ["org.nspasteboard.TransientType"],
            ["org.nspasteboard.AutoGeneratedType"],
            ["de.petermaurer.TransientPasteboardType"],
            ["net.p0deje.maccy.transient"],
            ["com.smileonmymac.textexpander.transient"]
        ]

        for types in sensitiveCases {
            let isSafe = filter.isSafeToSync(typeIdentifiers: types)
            #expect(!isSafe, "Expected types \(types) to be marked unsafe")
        }
    }

    @Test("Allows safe public types to synchronize")
    func testSafeTypesAllowed() {
        let safeCases: [[String]] = [
            ["public.utf8-plain-text"],
            ["public.png"],
            ["public.jpeg"],
            ["public.url"],
            ["public.rtf"],
            ["public.utf8-plain-text", "public.html"]
        ]

        for types in safeCases {
            let isSafe = filter.isSafeToSync(typeIdentifiers: types)
            #expect(isSafe, "Expected types \(types) to be marked safe")
        }
    }
}
